#!/usr/bin/env python3
"""Generate the Protoflow hand-off package for the CHOTU carrier PCB.

Protoflow (protoflow.ai, desktop app) is an AI PCB designer that produces a
KiCad project, runs ERC/DRC and exports JLCPCB fabrication files. It is driven
from its chat panel, so this script writes everything that panel needs - all
derived from ../chotu_carrier.py, the same tables that generate the KiCad
netlist and are cross-checked against the firmware pins.h by pytest:

    PROTOFLOW_BRIEF.md   - paste into Protoflow's chat (full spec + every net)
    bom_jlcpcb.csv       - BOM with suggested JLCPCB basic parts (LCSC numbers)
    chotu_carrier.net    - KiCad netlist (copied) for reference / review

    python hardware/pcb/protoflow/make_protoflow_package.py
"""
from __future__ import annotations

import csv
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import chotu_carrier as pcb  # noqa: E402

# Suggested JLCPCB *basic* parts for the SMD passives (no extended-part fee).
# Protoflow re-validates availability with its own JLC search before placing.
LCSC = {
    ("Resistor_SMD:R_0805_2012Metric", "100R"): "C17408",
    ("Resistor_SMD:R_0805_2012Metric", "1k"): "C17513",
    ("Resistor_SMD:R_0805_2012Metric", "2k"): "C17604",
    ("Resistor_SMD:R_0805_2012Metric", "4.7k"): "C17673",
    ("Resistor_SMD:R_0805_2012Metric", "10k"): "C17414",
    ("Resistor_SMD:R_0805_2012Metric", "22k"): "C17560",
    ("Resistor_SMD:R_0805_2012Metric", "100k"): "C17407",
    ("Capacitor_SMD:C_0805_2012Metric", "100nF"): "C49678",
    ("Capacitor_SMD:C_0805_2012Metric", "4.7uF"): "C1779",
}

BRIEF_HEAD = """# Protoflow brief - CHOTU carrier PCB v3

Paste everything below the line into Protoflow's chat. Generated by
`make_protoflow_package.py` from `hardware/pcb/chotu_carrier.py` - do not edit by hand.

---

Design a **2-layer, 1.6 mm FR-4 carrier PCB, 90 x 65 mm**, four M3 mounting holes 4 mm in from each corner
(they match the 3D-printed electronics deck in bot_3d_printing). It is the base-controller board of CHOTU, an
autonomous floor-cleaning robot: an **ESP32-S3-DevKitC-1 plugs into two 1x22 2.54 mm female headers**
(J1 left / J3 right, 25.4 mm row spacing) and every other module connects through JST-XH connectors on the
board edge. Fabrication target: **JLCPCB**, SMD passives 0805 from the JLC basic library, THT for connectors,
TO-220 MOSFETs and DO-201AD diodes. Hand-solderable.

## Electrical rules
- Power nets carrying motor/vacuum current - VBAT_RAW, VBAT_SW, VBAT, GND, VACUUM_D, BRUSH_D, MOT_* - use
  **2.0 mm traces** (vacuum branch peaks ~5 A); +5V 1.0 mm; all signals 0.3 mm. 0.2 mm min clearance.
- **Star ground**: the motor/vacuum return (Q1/Q2 sources, TB6612 GND, C1) meets logic ground at a single point
  next to J1 (XT60). Pour GND on the bottom layer.
- Keep Q1/Q2, D1/D2 and J17/J18 on one board edge away from the ESP32 antenna end (no copper under the antenna).
- C2 (1000 uF) within 10 mm of U2's OUT pads; C1 within 10 mm of J1.
- 5 V outputs of the HC-SR04 echoes and LM393 encoders must only reach the ESP32 through their 1k/2k dividers
  (nets *_ECHO_5V / ENC_*_5V never touch U1).
- Run ERC and DRC, then export Gerbers, drill, BOM, CPL (pick-and-place) and STEP for JLCPCB.

## Parts
| Ref | Value | Footprint |
|---|---|---|
"""


def main() -> int:
    errs = pcb.own_erc()
    if errs:
        print("design-rule check failed:", *errs, sep="\n  ")
        return 1
    with open(os.path.join(HERE, "PROTOFLOW_BRIEF.md"), "w", encoding="utf-8") as f:
        f.write(BRIEF_HEAD)
        for ref, (value, fp, _) in pcb.PARTS.items():
            f.write(f"| {ref} | {value} | `{fp}` |\n")
        f.write("\n## Netlist (every connection)\n| Net | Pins (ref.pin-name) |\n|---|---|\n")
        for net, members in sorted(pcb.nets().items()):
            f.write(f"| {net} | {', '.join(f'{r}.{p}' for r, p in members)} |\n")
        f.write("\n## ESP32-S3 GPIO map (must match firmware include/pins.h)\n| Signal | GPIO |\n|---|---|\n")
        for net, g in sorted(pcb.GPIO.items(), key=lambda kv: kv[1]):
            f.write(f"| {net} | GPIO{g} |\n")
        f.write("\nUnused DevKitC pins (RST, GPIO0/45/46 strapping, GPIO19/20 USB, GPIO35-37 PSRAM, GPIO48 RGB LED, "
                "TX/RX) are left unconnected.\n")
    with open(os.path.join(HERE, "bom_jlcpcb.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Comment", "Designator", "Footprint", "LCSC (suggested, JLC basic)"])
        groups = {}
        for ref, (value, fp, _) in pcb.PARTS.items():
            groups.setdefault((value, fp), []).append(ref)
        for (value, fp), refs in groups.items():
            w.writerow([value, ",".join(refs), fp, LCSC.get((fp, value), "hand-solder / module")])
    shutil.copy(os.path.join(os.path.dirname(HERE), "chotu_carrier.net"), os.path.join(HERE, "chotu_carrier.net"))
    print(f"Protoflow package written to {HERE} ({len(pcb.PARTS)} parts, {len(pcb.nets())} nets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
